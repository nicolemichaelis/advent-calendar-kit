#!/usr/bin/env python3
"""One command builds everything from config.json and your photos.

    python3 tools/build.py            full build (site, character, Telegram cards)
    python3 tools/build.py --no-cards skip the animated cards (Telegram then gets a plain text message)
    python3 tools/build.py --check    only check config.json and photos, change nothing

What it does:
  1. checks config.json and your 24 photos
  2. resizes photos into site/photos (phones make huge files)
  3. makes the delivery character (from your pet photo, or a paper envelope)
  4. writes site/content.js and netlify/lib/config.json
  5. renders 24 animated Telegram cards + a welcome card into site/cards
"""
import json, os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
args = set(sys.argv[1:])

def fail(msg): sys.exit("\nProblem: " + msg + "\n")
def note(msg): print("  " + msg)

# 1. config -------------------------------------------------------------------
try:
    cfg = json.load(open("config.json", encoding="utf-8"))
except json.JSONDecodeError as e:
    fail(f"config.json is not valid JSON ({e}). Look near that line for a missing comma or quote.")
for k in ("recipient", "from", "year", "timezone", "character", "days"):
    if k not in cfg: fail(f'config.json is missing "{k}".')
if not cfg["character"].get("name"): fail('character.name is empty.')
if cfg["style"]["wall"] not in ("forest", "navy", "burgundy", "charcoal"): fail('style.wall must be forest, navy, burgundy or charcoal.')
if cfg["style"]["cards"] not in ("festive", "nordic", "warm"): fail('style.cards must be festive, nordic or warm.')
sw = cfg.get("send_window", {})
if not (0 <= sw.get("from_hour", 8) < sw.get("to_hour", 20) <= 24): fail("send_window needs from_hour earlier than to_hour (0 to 24).")
try:
    from zoneinfo import ZoneInfo; ZoneInfo(cfg["timezone"])
except Exception:
    fail(f'timezone "{cfg["timezone"]}" is not a valid name. Use something like Europe/Stockholm or America/New_York.')

print("Checking your content")
missing, empty = [], []
for d in range(1, 25):
    day = cfg["days"].get(str(d))
    if not day: fail(f"config.json has no entry for day {d}.")
    if not day.get("title") or not day.get("letter"): empty.append(d)
    if not os.path.exists(f"photos/{d:02d}.jpg"): missing.append(d)
    if not day.get("note"): day["note"] = f"Door {d} is ready."
if empty: note("Days with no title or letter: " + ", ".join(map(str, empty)))
if missing: note("Days with no photo (a placeholder will show): " + ", ".join(f"{d:02d}.jpg" for d in missing))
if not (empty or missing): note("All 24 days have a title, a letter and a photo.")
if "--check" in args: sys.exit(0)

# 2. photos -------------------------------------------------------------------
from PIL import Image, ImageOps, ImageDraw
os.makedirs("site/photos", exist_ok=True)
print("Preparing photos")
for d in range(1, 25):
    src, dst = f"photos/{d:02d}.jpg", f"site/photos/{d:02d}.jpg"
    if os.path.exists(src):
        im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
        im.thumbnail((1600, 1600)); im.save(dst, "JPEG", quality=84, optimize=True, progressive=True)
    elif not os.path.exists(dst) or d in missing:
        ph = Image.new("RGB", (900, 1100), (222, 210, 188)); dr = ImageDraw.Draw(ph)
        dr.text((450, 550), f"photo {d:02d}", fill=(120, 108, 90), anchor="mm"); ph.save(dst, "JPEG", quality=80)

# 3. character ----------------------------------------------------------------
print("Making the delivery character")
photo = cfg["character"].get("photo") or ""
cmd = [sys.executable, "tools/make_character.py"]
has_pet = bool(photo) and os.path.exists(photo)
if has_pet:
    cmd.append(photo)
    if cfg["character"].get("face"): cmd.append("--face=" + cfg["character"]["face"])
r = subprocess.run(cmd)
if r.returncode != 0 and has_pet:
    note("Could not cut out the pet photo (see the message above). Using the paper envelope instead.")
    has_pet = False; subprocess.run([sys.executable, "tools/make_character.py"], check=True)

# 4. site + server config -----------------------------------------------------
print("Writing site and server files")
content = {
    "name": cfg["recipient"], "from": cfg["from"], "headline": cfg.get("headline", ""), "year": cfg["year"],
    "wall": cfg["style"]["wall"], "hasPet": has_pet, "testMode": False,
    "character": {"name": cfg["character"]["name"], "sign_off": cfg["character"].get("sign_off", "")},
    "days": {str(d): {"title": cfg["days"][str(d)]["title"], "message": cfg["days"][str(d)]["letter"], "note": cfg["days"][str(d)]["note"]} for d in range(1, 25)},
}
with open("site/content.js", "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build.py from config.json. Edit config.json, not this file. */\n")
    f.write("const CONFIG = " + json.dumps(content, indent=2, ensure_ascii=False) + ";\n")
use_cards = cfg.get("cards", True) and "--no-cards" not in args
server = {"year": cfg["year"], "timezone": cfg["timezone"], "send_window": sw or {"from_hour": 8, "to_hour": 20},
          "special_days": [6, 21, 24], "cards": use_cards, "character": cfg["character"],
          "welcome_message": cfg.get("welcome_message", ""),
          "days": {str(d): {"note": cfg["days"][str(d)]["note"]} for d in range(1, 25)}}
server["character"] = {"name": cfg["character"]["name"], "sign_off": cfg["character"].get("sign_off", "")}
json.dump(server, open("netlify/lib/config.json", "w", encoding="utf-8"), indent=2, ensure_ascii=False)

# 5. cards --------------------------------------------------------------------
if use_cards:
    print("Rendering Telegram cards (24 animated cards, a few minutes)")
    ok = shutil.which("ffmpeg") is not None
    try:
        import playwright  # noqa
    except ImportError:
        ok = False
    if not ok:
        note("Cards need ffmpeg and playwright (see README, step 3). Skipping them: Telegram will get a plain text message with the button.")
        server["cards"] = False; json.dump(server, open("netlify/lib/config.json", "w", encoding="utf-8"), indent=2, ensure_ascii=False)
    else:
        cd = os.path.join("tools", "cards")
        subprocess.run([sys.executable, "gen.py"], cwd=cd, check=True)
        subprocess.run([sys.executable, "gen.py", "0"], cwd=cd, check=True)
        subprocess.run([sys.executable, "render.py", "video"], cwd=cd, check=True)
        subprocess.run([sys.executable, "render.py", "video", "0"], cwd=cd, check=True)
        os.makedirs("site/cards", exist_ok=True)
        for d in range(1, 25): shutil.copy(f"{cd}/out/{d:02d}.mp4", f"site/cards/{d:02d}.mp4")
        shutil.copy(f"{cd}/out/00.mp4", "site/cards/welcome.mp4")
print("\nDone. Next: open README.md, step 4 (put it online).")
